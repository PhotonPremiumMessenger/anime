/** Рисует список обновлений. */
function renderUpdates(containerId = 'updatesList') {
  const box = document.getElementById(containerId);
  if (!box) return;

  box.innerHTML = ANILINGO_UPDATES.map(release => `
    <article class="update-card">
      <div class="update-head">
        <span class="update-version">${release.version}</span>
        <time>${new Date(release.date).toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' })}</time>
      </div>
      <h3>${release.title}</h3>
      <ul class="update-list">
        ${release.items.map(item => `<li>${item}</li>`).join('')}
      </ul>
    </article>
  `).join('');
}

document.addEventListener('DOMContentLoaded', () => renderUpdates());

/* Экспорт в глобальную область */
window.ANILINGO_UPDATES = ANILINGO_UPDATES;
window.renderUpdates = renderUpdates;
